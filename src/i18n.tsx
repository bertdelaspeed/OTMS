const MESSAGES: Record<Lang, Record<string, string>> = { en, fr };

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  /** plural-aware: picks `${key}_one` / `${key}_many` and injects n */
  tp: (key: string, n: number, vars?: Record<string, string | number>) => string;
}

const Ctx = createContext<I18nCtx | null>(null);

function interpolate(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    const saved = (localStorage.getItem("rollcall.lang") as Lang | null) ?? "en";
    const l: Lang = saved === "fr" ? "fr" : "en";
    setDateLocale(l);
    return l;
  });

  useEffect(() => {
    localStorage.setItem("rollcall.lang", lang);
    setDateLocale(lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t: I18nCtx["t"] = (key, vars) =>
    interpolate(MESSAGES[lang][key] ?? MESSAGES.en[key] ?? key, vars);
  const tp: I18nCtx["tp"] = (key, n, vars) =>
    t(n === 1 ? `${key}_one` : `${key}_many`, { n, ...vars });

  return <Ctx.Provider value={{ lang, setLang, t, tp }}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
